    if title_tag:
        title = title_tag.text.strip()
    else:
        continue

    model_id = np.nan
    launch_year = np.nan
    sound_output = np.nan
    warranty = np.nan

    specs = tv.select('li.DTBslk')

    for spec in specs:
        text = spec.text.strip()

        if "Model ID:" in text:
            model_id = text.replace("Model ID:", "").strip()

        if "Launch Year:" in text:
            year = re.search(r'20\d{2}', text)
            if year:
                launch_year = int(year.group())

        if "Total Sound Output:" in text:
            sound = re.search(r'(\d+\.?\d*)\s*W', text)
            if sound:
                sound_output = float(sound.group(1))

        if "Warranty" in text:
            years = re.search(r'(\d+)\s*Year', text, re.I)
            if years:
                warranty = int(years.group(1))

