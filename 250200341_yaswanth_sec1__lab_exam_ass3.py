BASE_URL = "https://www.oyorooms.com/hotels-in-chennai/"

HEADERS = {
    "User-Agent": "Mozilla/5.0"
}

def extract_number(text):
    if text is None:
        return None
    match = re.search(r'[\d,]+(?:\.\d+)?', str(text))
    if match:
        return float(match.group().replace(",", ""))
    return None

hotel_data = []

for page in range(1, 6):
    url = f"{BASE_URL}?page={page}"
    response = requests.get(url, headers=HEADERS)

    if response.status_code != 200:
        continue

    soup = BeautifulSoup(response.content, "html.parser")

    hotels = soup.find_all(
        "div",
        class_="oyo-row oyo-row--no-spacing hotelCardListing"
    )

    for hotel in hotels:
        try:
            title = hotel.h3["title"]
        except:
            title = None

        try:
            address = hotel.find(
                "span",
                class_="u-line--clamp-2"
            )["title"]
        except:
            address = None

        try:
            rating_count = hotel.find(
                "span",
                class_="hotelRating__ratingSummary hotelRating__rating--clickable"
            ).text.strip()
        except:
            rating_count = None

        try:
            star_rating = hotel.find(
                "span",
                class_="hotelRating__rating"
            ).text.strip()
        except:
            star_rating = None

        try:
            price = hotel.find(
                "span",
                class_="listingPrice__finalPrice listingPrice__finalPrice--black"
            ).text.strip()
        except:
            price = None

        hotel_data.append({
            "Title": title,
            "Address": address,
            "Price": extract_number(price),
            "Star_Rating": extract_number(star_rating),
            "Rating_Count": extract_number(rating_count)
        })

    time.sleep(1)

df = pd.DataFrame(hotel_data)

