mobiles = soup.find_all("div", class_="jIjQ8S")

data = []

def get_number(text):
    if text is None:
        return None
    match = re.search(r"[\d,]+(?:\.\d+)?", str(text))
    if match:
        return float(match.group().replace(",", ""))
    return None

for mobile in mobiles:
    try:
        title = mobile.find("div", class_="RG5Slk").text.strip()
    except:
        title = None

    try:
        price = mobile.find("div", class_="hZ3P6w").text.strip()
    except:
        try:
            price = mobile.find(
                "div",
                class_=lambda value: value and "Nx9bqj" in value
            ).text.strip()
        except:
            price = None

    specifications = [
        item.text.strip()
        for item in mobile.find_all("li", class_="DTBslk")
    ]

    ram = None
    rom = None
    rear_camera = None
    front_camera = None
    battery = None
    processor = None
    warranty = None

    for specification in specifications:
        lower_text = specification.lower()

        if "ram" in lower_text and "rom" in lower_text:
            ram_match = re.search(
                r"(\d+(?:\.\d+)?)\s*GB\s*RAM",
                specification,
                re.I
            )

            rom_match = re.search(
                r"(\d+(?:\.\d+)?)\s*GB\s*ROM",
                specification,
                re.I
            )

            if ram_match:
                ram = float(ram_match.group(1))

            if rom_match:
                rom = float(rom_match.group(1))

        if "camera" in lower_text:
            camera_values = re.findall(
                r"(\d+(?:\.\d+)?)\s*MP",
                specification,
                re.I
            )

            if camera_values:
                rear_camera = float(camera_values[0])

                if len(camera_values) > 1:
                    front_camera = float(camera_values[-1])

        if "battery" in lower_text:
            battery_match = re.search(
                r"(\d+(?:\.\d+)?)\s*mAh",
                specification,
                re.I
            )

